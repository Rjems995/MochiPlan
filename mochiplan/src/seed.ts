const e = (
  title: string,
  day: number,
  start: number,
  end: number,
  color: string,
  location: string,
): Entry => ({
  id: uid(),
  title,
  day,
  start,
  end,
  color,
  location,
  instructor: "",
  notes: "",
});
export function makeSchedule(
  name = "Untitled planner",
  type = "Weekly planner",
  themeId = "strawberry",
): Schedule {
  const theme = themes.find((t) => t.id === themeId) || themes[0];
  return {
    id: uid(),
    name,
    title: name,
    type,
    entries: [],
    design: defaultDesign(theme),
    updatedAt: Date.now(),
  };
}
